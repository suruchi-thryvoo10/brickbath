const bySlug = new Map(products.map((p) => [p.slug, p]));

export function getProduct(slug: string): Product | undefined {
  return bySlug.get(slug);
}

export function getProducts(slugs: string[]): Product[] {
  return slugs.map((s) => bySlug.get(s)).filter((p): p is Product => Boolean(p));
}

export function productsByCategory(category: CategorySlug): Product[] {
  return products.filter((p) => p.category === category);
}

export function featuredProducts(limit = 8): Product[] {
  return products.filter((p) => p.featured).slice(0, limit);
}

export function bestSellers(limit = 8): Product[] {
  return products.filter((p) => p.bestSeller).slice(0, limit);
}

export function newArrivals(limit = 8): Product[] {
  return [...products]
    .filter((p) => p.newArrival)
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .slice(0, limit);
}

/**
 * Related products: same category first, then anything sharing a style or
 * finish, scored so the closest matches surface first.
 */
export function relatedProducts(product: Product, limit = 4): Product[] {
  const scored = products
    .filter((p) => p.slug !== product.slug)
    .map((p) => {
      let score = 0;
      if (p.category === product.category) score += 5;
      if (p.subCategory === product.subCategory) score += 3;
      if (p.brand === product.brand) score += 2;
      score += p.styles.filter((s) => product.styles.includes(s)).length * 2;
      score += p.finishes.filter((f) => product.finishes.includes(f)).length;
      if (p.priceTier === product.priceTier) score += 1;
      return { p, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || b.p.rating - a.p.rating);

  return scored.slice(0, limit).map((x) => x.p);
}

/** Products that finish the room — deliberately from *other* categories. */
export function completeTheLook(product: Product, limit = 4): Product[] {
  return products
    .filter((p) => p.category !== product.category)
    .map((p) => ({
      p,
      score:
        p.styles.filter((s) => product.styles.includes(s)).length * 3 +
        p.finishes.filter((f) => product.finishes.includes(f)).length * 2 +
        (p.priceTier === product.priceTier ? 2 : 0) +
        (p.featured ? 1 : 0),
    }))
    .sort((a, b) => b.score - a.score || b.p.rating - a.p.rating)
    .slice(0, limit)
    .map((x) => x.p);
}

